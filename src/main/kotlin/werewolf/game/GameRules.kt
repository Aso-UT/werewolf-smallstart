package werewolf.game

// ゲームのルール説明。どのプレイヤーにも同じルールが適用される
object GameRules {
    val description = """
役職構成：人狼2・狂人1・村人3・占い師1・霊能者1・狩人1（計9人）
人狼は仲間の人狼を知っていますが狂人が誰かは知りません。狂人も人狼が誰かを知りません。また、ほかの役職も他人の役職は知りません。

【勝利条件】
村人（村人・占い師・霊能者・狩人）：人狼が全員死亡すれば勝利
狂人：人狼が勝利したとき自分も勝利。ただし人数上は村人側として数えられる
人狼：生存する人狼の数が村人側（狂人含む）の数以上になれば勝利

【夜のルール】
・人狼は毎晩3往復の密談ができます。
　初日は襲撃ができません。二日目以降は人狼以外のプレイヤーを一人選んで襲撃できます。襲撃先が人狼間で割れた場合は襲撃先候補からランダムに一人が襲撃されます。
・占い：毎晩一人のプレイヤーが人狼（黒）か、人狼以外（白。狂人も白扱いとなることに注意）かを知ることができます。
　初日は人狼以外のプレイヤーからランダムに1人が占われます。よって必ず結果は白となります。
　2日目以降は占い師が対象を選びます。
・霊能：前日に処刑されたプレイヤーが人狼（黒）か人狼以外（白。狂人も白扱いとなることに注意）かを知ることができます。
　初日は「前日の処刑」がないので霊能結果は得られません。
・狩人は自分以外のプレイヤーを一人選んで護衛できます。護衛先と襲撃先が一致した場合襲撃はなくなります（護衛成功）。
　初日は襲撃がないため護衛先の選択もしません。

【昼のルール】
・議論：発言したい度合いが最も高い人が発言します。同じ人が続けて発言することはできず、一人が発言できるのは最大4回までです。発言の合計が生存者数×3回に達すると議論は終わります
・発言者名は別途表示されるため、発言内で自分の名前を名乗る必要はありません
・投票：投票先は他のプレイヤーに開示されません。最多票のプレイヤーが処刑されます

【ローカルルール：対抗COの義務】
・CO：自分の役職を名乗ることです（例：「私は占い師です」）。占い結果・霊能結果を報告することは、それぞれ占い師・霊能者のCOを兼ねます。
・対抗CO：直前にCOされたのと同じ役職を、別の人が名乗ることです。違う役職を名乗るのは、対抗COではなく通常のCOです。
・ある役職のCOが出たとき、その役職に就く人、またはその役職を騙ろうとする人は、最初のCOに続いてすぐさま対抗COしなければなりません。
・最初のCOから後は、対抗CO以外の発言が一つでも挟まると、それ以降の対抗COは認められません。
　例：
　　占い師CO → 占い師CO（有効）→ 占い師CO（有効）
　　占い師CO → 通常の発言 → 占い師CO（無効）
　　占い師CO → 霊能者CO（有効だが対抗COではない）→ 占い師CO（無効）
・誰が真の役職者かを論理的に判断しやすくするため、このルールを設けています。

【ローカルルール：言葉の使い分け】
議論では、次の言葉を定義どおりに使ってください。

■ 確定
・全員が見られる情報（誰が何を発言したか、誰が死んだか、ローカルルール）だけから、論理的に必ず導けることを「確定」と言います。
・占い・霊能の結果が、あとで事実と違うとわかれば、その人の偽は確定します（例：黒と言った相手が襲撃で死んだ。襲撃されるのは人狼以外です）。
・結果が、あとで正しかったとわかっても、その人の真は確定しません。偽物も正しい結果を言えるからです。
・同じ役職の候補のうち、ほかの全員の偽が確定すれば、残った一人の真が確定します。
・対抗COの義務により、ある役職のCOに対抗COが出なければ、そのCOをした人の真は確定します。ただし、死んだプレイヤーの中にその役職でありえた人がいる場合は確定しません。本物が名乗る前に死んでいるかもしれないからです。

■ X目線確定
・X だけが知っている情報（自分の役職、自分の占い・霊能結果、人狼仲間など）を合わせれば必ず導けることを「X目線確定」と言います（例：真占い師は、対抗の占い師が偽だと知っています。これは「〇〇目線確定」です）。
・ほかの人には検証できないので、議論で単に「確定」とは言わないでください。

■ 確定していないことの評価
・真目：ある役職をCOした人が、本物である見込みです。「真目が高い／低い」と言います。
・村目：村側（村人・占い師・霊能者・狩人）である見込みです。狂人は人狼側なので、村目には入りません。
・白い／黒い：人狼でない／人狼である見込みです。占い・霊能結果の白黒から来た言葉なので、狂人は白に入ります。
・村目と白黒の違いは、狂人の扱いです（村目は狂人を除き、白は狂人を含みます）。

【ローカルルール：積極的な発言の推奨】
・この村では積極的・論理的であることが正義です。誰かを疑う言葉は議論を盛り上げるため歓迎されます。
・「攻撃的なのは人狼よりだ」などといった偏見は捨ててください。
